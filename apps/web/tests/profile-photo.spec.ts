import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {register} from './helpers/register';
test.use({trace:'off'});
test('profile photo upload persists, shares under privacy rules and removes',async({page,request,browser},testInfo)=>{
 await register(page,request,'Photo');
 const edit=page.getByRole('button',{name:'Edit profile photo',exact:true});
 const modal=page.getByRole('dialog',{name:'Profile photo',exact:true});
 const controls=page.getByRole('region',{name:'Profile photo',exact:true});
 await expect(controls).not.toBeVisible();await edit.focus();await page.keyboard.press('Enter');await expect(modal).toBeVisible();
 await page.keyboard.press('Escape');await expect(modal).not.toBeVisible();await expect(edit).toBeFocused();
 await edit.click();
 await controls.getByLabel('Choose profile photo').setInputFiles({name:'invalid.txt',mimeType:'text/plain',buffer:Buffer.from('not a photo')});
 await expect(controls.getByText('Choose a JPEG or PNG file up to 2 MiB.',{exact:true})).toBeVisible();
 await expect(modal.getByRole('button',{name:'Save photo',exact:true})).toBeDisabled();
 const bytes=Buffer.from(await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=120;canvas.height=120;const ctx=canvas.getContext('2d')!;ctx.fillStyle='#24756c';ctx.fillRect(0,0,120,120);return canvas.toDataURL('image/png').split(',')[1]}),'base64');
 await controls.getByLabel('Choose profile photo').setInputFiles({name:'portrait.png',mimeType:'image/png',buffer:bytes});
 await expect(page.getByAltText('Selected profile photo preview')).toBeVisible();
 page.once('dialog',dialog=>dialog.dismiss());await modal.getByRole('button',{name:'Cancel',exact:true}).click();await expect(modal).toBeVisible();
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
 await page.screenshot({path:testInfo.outputPath('photo-dialog-desktop.png'),fullPage:true});
 await page.route('**/api/v1/me/photo',route=>route.request().method()==='PUT'?route.abort():route.continue());
 await modal.getByRole('button',{name:'Save photo',exact:true}).click();await expect(controls.locator('.photo-error')).not.toBeEmpty();await expect(modal).toBeVisible();
 await page.unroute('**/api/v1/me/photo');
 await modal.getByRole('button',{name:'Save photo',exact:true}).click();
 await expect(page.getByText('Profile photo saved.',{exact:true})).toBeVisible();await expect(modal).not.toBeVisible();await expect(edit).toBeFocused();
 const photo=page.getByAltText("Photo Member's profile photo",{exact:true});
 await expect(photo).toBeVisible();await page.reload();await expect(photo).toBeVisible();
 await expect.poll(()=>photo.evaluate((el:HTMLImageElement)=>el.naturalWidth)).toBe(120);
 const settings=page.getByRole('region',{name:'Profile visibility',exact:true});
 const path=(await settings.getByRole('link',{name:'View member profile'}).getAttribute('href'))!;
 const context=await browser.newContext();try{
 const guest=await context.newPage();
 expect((await guest.request.get(`http://localhost:3100/api/v1/profiles/${path.split('/').pop()}/photo`)).status()).toBe(401);
 await settings.getByRole('checkbox',{name:'Public profile — visible without signing in'}).click();await expect(settings.getByText('Visibility saved.',{exact:true})).toBeVisible();
 await guest.goto(path);await expect(guest.getByAltText("Photo Member's profile photo",{exact:true})).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
 await page.screenshot({path:testInfo.outputPath('profile-photo-mobile.png'),fullPage:true});
 await edit.click();await page.emulateMedia({colorScheme:'dark'});await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:testInfo.outputPath('photo-dialog-mobile-dark.png'),fullPage:true});
 await modal.getByRole('button',{name:'Remove photo',exact:true}).click();
 const removal=page.getByRole('dialog',{name:'Remove profile photo?',exact:true});await expect(removal).toBeVisible();
 await removal.getByRole('button',{name:'Keep photo',exact:true}).click();await expect(modal).toBeVisible();
 await modal.getByRole('button',{name:'Remove photo',exact:true}).click();await removal.getByRole('button',{name:'Confirm removal',exact:true}).click();
 await expect(page.getByText('Profile photo removed.',{exact:true})).toBeVisible();
 await page.reload();await expect(photo).toHaveCount(0);
 await guest.reload();await expect(guest.getByAltText("Photo Member's profile photo",{exact:true})).toHaveCount(0);
 }finally{await context.close()}
});
