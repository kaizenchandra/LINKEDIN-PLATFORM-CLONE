import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {register} from './helpers/register';
test.use({trace:'off'});
test('reference-inspired profile works at desktop, mobile and dark sizes',async({page,request},testInfo)=>{
 await page.setViewportSize({width:1440,height:1000});
 await register(page,request,'Taylor');
 await page.getByRole('combobox',{name:'Appearance'}).selectOption('light');
 await page.getByRole('button',{name:'Edit introduction',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('textbox',{name:'headline',exact:true}).fill('Product designer · Building thoughtful digital experiences');
 await page.getByRole('textbox',{name:'location',exact:true}).fill('Bengaluru, Karnataka, India');
 await page.getByRole('textbox',{name:'about',exact:true}).fill('I bring people, systems, and ideas together to make useful products. Interested in accessible design, collaborative teams, and the small details that make a difference.');
 await page.getByRole('button',{name:'Save profile',exact:true}).click();
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await page.getByRole('button',{name:'Add experience',exact:true}).click();
 await page.getByRole('textbox',{name:'Job title',exact:true}).fill('Senior Product Designer');
 await page.getByRole('textbox',{name:'Organization',exact:true}).fill('Northstar Studio (fictional)');
 await page.getByLabel('Start date',{exact:true}).fill('2022-04-01');
 await page.getByRole('button',{name:'Save experience',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Senior Product Designer',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Edit introduction',exact:true}).click();
 await page.getByRole('textbox',{name:'headline',exact:true}).fill('Unsaved edit');
 page.once('dialog',dialog=>dialog.accept());
 await page.keyboard.press('Escape');
 await expect(page.getByText('Unsaved edit',{exact:true})).toHaveCount(0);
 await page.getByRole('textbox',{name:'Find a profile section'}).fill('Skills');
 await page.getByRole('textbox',{name:'Find a profile section'}).press('Enter');
 await expect(page).toHaveURL(/#skills$/);
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Taylor Member',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Senior Product Designer',exact:true})).toBeVisible();
 await page.screenshot({path:testInfo.outputPath('desktop-light.png')});
 expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([]);
 await page.getByRole('combobox',{name:'Appearance'}).selectOption('dark');
 await expect(page.getByText('Appearance saved to your account.',{exact:true})).toBeVisible();
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:testInfo.outputPath('desktop-dark.png')});
 expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([]);
 await page.getByRole('combobox',{name:'Appearance'}).selectOption('light');
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>window.scrollTo(0,0));
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:testInfo.outputPath('mobile-light.png')});
 await page.locator('.account-menu summary').click();
 await expect(page.getByRole('link',{name:'Account security',exact:true})).toBeVisible();
 await page.locator('.account-menu summary').click();
 await page.getByRole('button',{name:'Edit introduction',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.screenshot({path:testInfo.outputPath('mobile-editor.png')});
 expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([]);
 await page.getByRole('button',{name:'Close introduction editor'}).click();
});
