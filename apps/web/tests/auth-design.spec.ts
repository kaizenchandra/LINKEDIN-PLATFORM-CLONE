import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {register} from './helpers/register';
test.use({trace:'off'});
test('screenshot-inspired welcome and identity forms lead to verified registration',async({page,request},testInfo)=>{
 await page.goto('/');await expect(page.getByRole('heading',{name:'Explore opportunities. Grow your professional network.'})).toBeVisible();
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
 await page.screenshot({path:testInfo.outputPath('welcome-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:testInfo.outputPath('welcome-mobile.png'),fullPage:true});
 await page.getByRole('link',{name:'Sign in with email',exact:true}).click();
 await expect(page).toHaveURL(/code_challenge_method=S256/);await expect(page.locator('link[href*="meridian.css"]')).toHaveCount(1);
 await expect(page.getByRole('textbox',{name:'Email',exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'Forgot Password?',exact:true})).toBeVisible();
 await page.locator('input[name="password"]').fill('Preview-only-not-a-credential');
 const toggle=page.locator('button[data-password-toggle]');await toggle.click();await expect(page.locator('input[name="password"]')).toHaveAttribute('type','text');await toggle.click();await expect(page.locator('input[name="password"]')).toHaveAttribute('type','password');
 await page.locator('input[name="password"]').fill('');
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:testInfo.outputPath('login-mobile.png'),fullPage:true});
 await page.setViewportSize({width:1440,height:1000});await page.screenshot({path:testInfo.outputPath('login-desktop.png'),fullPage:true});
 await page.getByRole('link',{name:'Register',exact:true}).click();await expect(page.getByRole('heading',{name:'Join Meridian — build your next chapter'})).toBeVisible();
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
 await page.screenshot({path:testInfo.outputPath('register-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});await page.emulateMedia({colorScheme:'dark'});
 expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:testInfo.outputPath('register-mobile-dark.png'),fullPage:true});
 await register(page,request,'Join',true);
 await expect(page.getByRole('heading',{name:'Join Member',exact:true})).toBeVisible();
 expect((await page.request.get('/api/v1/me')).status()).toBe(200);
});
