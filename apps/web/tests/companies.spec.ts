import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {register} from './helpers/register';
test.use({trace:'off'});
test('company owners publish and edit while other members discover and follow',async({page,request,browser},testInfo)=>{
 test.setTimeout(90000);
 await register(page,request,'CompanyOwner');
 await page.locator('.account-menu summary').click();await page.getByRole('link',{name:'Companies',exact:true}).click();
 await page.getByRole('link',{name:'Create company page',exact:true}).click();
 const name='Northstar Fictional '+Date.now();
 await page.getByLabel('Company name',{exact:true}).fill(name);
 await page.getByLabel('Industry',{exact:true}).fill('Design technology');
 await page.getByLabel('Location',{exact:true}).fill('Bengaluru, India');
 await page.getByRole('textbox',{name:'About company',exact:true}).fill('Fictional studio building accessible professional tools.');
 await page.getByRole('button',{name:'Save company',exact:true}).click();
 await expect(page).toHaveURL(/\/companies\/[0-9a-f-]{36}$/);
 const url=page.url(),id=url.split('/').pop();
 await expect(page.getByRole('heading',{name,exact:true})).toBeVisible();
 await page.reload();await expect(page.getByText('Fictional studio building accessible professional tools.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Edit company',exact:true}).click();
 await page.getByRole('textbox',{name:'About company',exact:true}).fill('Unsaved company edit');
 page.once('dialog',dialog=>dialog.accept());await page.getByRole('button',{name:'Cancel company changes',exact:true}).click();
 await expect(page.getByText('Unsaved company edit',{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Edit company',exact:true}).click();
 await page.getByRole('textbox',{name:'About company',exact:true}).fill('Persisted company overview.');
 await page.getByRole('button',{name:'Save company',exact:true}).click();
 await expect(page.getByRole('status')).toHaveText('Company saved.');
 await page.reload();await expect(page.getByText('Persisted company overview.',{exact:true})).toBeVisible();
 // Concurrent owner session changes are real API writes, not a mocked conflict response.
 await page.getByRole('button',{name:'Edit company',exact:true}).click();
 await page.getByRole('textbox',{name:'About company',exact:true}).fill('Stale browser edit');
 const saved=await (await page.request.get('/api/v1/organizations/'+id)).json();
 const csrf=await (await page.request.get('/api/v1/csrf')).json();
 expect((await page.request.put('/api/v1/organizations/'+id,{headers:{[csrf.header]:csrf.token},data:{...saved,about:'Concurrent persisted overview.'}})).ok()).toBeTruthy();
 await page.getByRole('button',{name:'Save company',exact:true}).click();
 await expect(page.getByRole('status')).toHaveText('Company changed or request conflicts. Cancel edits and refresh before retrying.');
 await expect(page.getByRole('textbox',{name:'About company',exact:true})).toHaveValue('Stale browser edit');
 page.once('dialog',dialog=>dialog.accept());await page.getByRole('button',{name:'Cancel company changes',exact:true}).click();
 await page.getByRole('button',{name:'Refresh company',exact:true}).click();
 await expect(page.getByText('Concurrent persisted overview.',{exact:true})).toBeVisible();
 const context=await browser.newContext();try{
  const member=await context.newPage();await register(member,request,'CompanyFollower');
  await member.goto('/companies');await member.getByLabel('Company name or industry').fill(name);await member.getByRole('button',{name:'Search companies',exact:true}).click();
  await expect(member.getByRole('button',{name:'Search companies',exact:true})).toBeEnabled();
  await expect(member.getByRole('article')).toHaveCount(1);
  await member.getByRole('article',{name:'Company '+name,exact:true}).getByRole('link',{name:'View company',exact:true}).click();
  await expect(member.getByRole('heading',{name,exact:true})).toBeVisible();
  await expect(member.getByRole('button',{name:'Edit company',exact:true})).toHaveCount(0);
  const otherCsrf=await (await member.request.get('/api/v1/csrf')).json();
  expect((await member.request.put('/api/v1/organizations/'+id,{headers:{[otherCsrf.header]:otherCsrf.token},data:{...saved,about:'Unauthorized rewrite'}})).status()).toBe(403);
  await member.getByRole('button',{name:'Follow company',exact:true}).click();
  await expect(member.getByText('1 followers',{exact:true})).toBeVisible();
  await member.reload();await expect(member.getByRole('button',{name:'Unfollow company',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Refresh company',exact:true}).click();await expect(page.getByText('1 followers',{exact:true})).toBeVisible();
  await member.goto('/companies');await member.getByRole('button',{name:'Followed companies',exact:true}).click();
  await expect(member.getByRole('link',{name,exact:true})).toBeVisible();
  await member.getByRole('article',{name:'Company '+name,exact:true}).getByRole('link',{name:'View company',exact:true}).click();
  expect((await new AxeBuilder({page:member}).analyze()).violations).toEqual([]);
  await member.screenshot({path:testInfo.outputPath('company-desktop.png'),fullPage:true});
  await member.setViewportSize({width:390,height:844});
  expect(await member.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  expect((await new AxeBuilder({page:member}).analyze()).violations).toEqual([]);
  await member.screenshot({path:testInfo.outputPath('company-mobile-dark.png'),fullPage:true});
  await member.getByRole('button',{name:'Unfollow company',exact:true}).click();await expect(member.getByText('0 followers',{exact:true})).toBeVisible();
  await member.goto('/companies');await member.getByRole('button',{name:'Followed companies',exact:true}).click();
  await expect(member.getByRole('status')).toHaveText('No companies match this view.');
 }finally{await context.close()}
 await page.goto('/companies');await page.getByRole('button',{name:'Managed companies',exact:true}).click();
 await expect(page.getByRole('link',{name,exact:true})).toBeVisible();
});
