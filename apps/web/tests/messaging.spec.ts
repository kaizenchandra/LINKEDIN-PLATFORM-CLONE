import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {register} from './helpers/register';
test.use({trace:'off'});
test('durable messages deliver to a second member, acknowledge reads and recover offline',async({page,request,browser},testInfo)=>{
 await register(page,request,'ChatA');
 const visibility=page.getByRole('region',{name:'Profile visibility',exact:true});
 await visibility.getByRole('checkbox',{name:'Visible to signed-in members',exact:true}).click();await expect(visibility.getByRole('checkbox',{name:'Visible to signed-in members',exact:true})).toBeChecked();
 const path=await visibility.getByRole('link',{name:'View member profile'}).getAttribute('href');
 test.setTimeout(90000);
 let releaseLost=()=>{};const lostResponse=new Promise<void>(resolve=>{releaseLost=resolve});
 const frames:string[]=[];page.on('websocket',ws=>{if(ws.url().endsWith('/api/v1/realtime'))ws.on('framereceived',event=>frames.push(String(event.payload)))});
 const second=await browser.newContext();
 try{
  const b=await second.newPage();await register(b,request,'ChatB');await b.goto('http://localhost:3100'+path);
  await b.getByRole('button',{name:'Message',exact:true}).click();
  await expect(b.getByText('Messaging requires an accepted connection and no block.',{exact:true})).toBeVisible();
  await b.getByRole('button',{name:'Connect',exact:true}).click();await expect(b.getByText('Connection request sent.',{exact:true})).toBeVisible();
  const network=page.getByRole('region',{name:'My network',exact:true});
  await network.getByRole('button',{name:'Reload network',exact:true}).click();
  await network.getByRole('button',{name:'Accept invitation',exact:true}).click();await expect(network.getByText('Connections: 1',{exact:true})).toBeVisible();
  await b.getByRole('button',{name:'Message',exact:true}).click();await expect(b).toHaveURL(/messages\?conversation=/);
  await expect(b.getByRole('textbox',{name:'Message',exact:true})).toBeVisible();
  await page.goto('/messages');
  await expect(page.getByText('Live updates connected.',{exact:true})).toBeVisible();
  await expect(b.getByText('Live updates connected.',{exact:true})).toBeVisible();
  const beforeSignal=frames.length;
  const hello='Hello from a connection '+Date.now();
  await b.getByRole('textbox',{name:'Message',exact:true}).fill(hello);await b.getByRole('button',{name:'Send message',exact:true}).click();
  await expect(b.getByRole('article',{name:'Sent message',exact:true}).filter({hasText:hello})).toBeVisible();
  await expect.poll(()=>frames.length).toBeGreaterThan(beforeSignal);
  for(const payload of frames)expect(JSON.parse(payload)).toEqual({version:1,type:'refresh'});
  const conversation=page.getByRole('button',{name:/ChatB Member/});
  await expect(conversation).toContainText('1 unread',{timeout:15000});
  await conversation.click();await expect(page.getByRole('article',{name:'Received message',exact:true}).filter({hasText:hello})).toBeVisible();
  await expect(b.getByRole('article',{name:'Sent message',exact:true}).filter({hasText:hello})).toContainText('Read',{timeout:15000});
  // Persist a send but deliberately lose its response; retry must reuse the same UUID.
  const uncertain='A retry-safe reply '+Date.now();
  await page.route('**/api/v1/conversations/*/messages/*',async route=>{try{const result=await route.fetch();if(!result.ok())throw Error('Send did not persist');await lostResponse;await route.abort('failed')}catch{if(!page.isClosed())await route.abort('failed').catch(()=>{})}});
  await page.getByRole('textbox',{name:'Message',exact:true}).fill(uncertain);await page.getByRole('button',{name:'Send message',exact:true}).click();
  await expect(page.getByRole('region',{name:'Conversation',exact:true}).getByRole('alert')).toHaveText('Request timed out. Check history before retrying.',{timeout:15000});
  await expect(page.getByRole('textbox',{name:'Message',exact:true})).toHaveValue(uncertain);
  await expect(b.getByRole('article',{name:'Received message',exact:true}).filter({hasText:uncertain})).toHaveCount(1,{timeout:15000});
  releaseLost();
  await page.unroute('**/api/v1/conversations/*/messages/*');
  await page.getByRole('button',{name:'Send message',exact:true}).click();
  await expect(page.getByRole('textbox',{name:'Message',exact:true})).toHaveValue('');
  await expect(b.getByRole('article',{name:'Received message',exact:true}).filter({hasText:uncertain})).toHaveCount(1,{timeout:15000});
  await page.context().setOffline(true);
  const missed='Delivered after reconnect '+Date.now();
  await b.getByRole('textbox',{name:'Message',exact:true}).fill(missed);await b.getByRole('button',{name:'Send message',exact:true}).click();
  await expect(b.getByRole('textbox',{name:'Message',exact:true})).toHaveValue('');
  await expect(page.getByRole('status')).toHaveText('Connection interrupted. Retrying automatically.',{timeout:15000});
  await page.context().setOffline(false);
  await expect(page.getByText('Live updates connected.',{exact:true})).toBeVisible({timeout:30000});
  await expect(page.getByRole('article',{name:'Received message',exact:true}).filter({hasText:missed})).toHaveCount(1,{timeout:30000});
  await page.reload();await page.getByRole('button',{name:/ChatB Member/}).click();
  await expect(page.getByText(missed,{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Star conversation',exact:true}).click();
  await expect(page.getByRole('button',{name:'Unstar conversation',exact:true})).toBeVisible();
  await page.reload();await page.getByRole('button',{name:/ChatB Member/}).click();
  await expect(page.getByRole('button',{name:'Unstar conversation',exact:true})).toBeVisible();
  await page.getByRole('textbox',{name:'Find conversations by name',exact:true}).fill('chatb');
  await page.getByRole('button',{name:'Search conversations',exact:true}).click();
  await page.getByRole('button',{name:'Starred',exact:true}).click();
  await expect(page.getByRole('button',{name:/ChatB Member/})).toBeVisible();
  await page.getByRole('button',{name:'Inbox',exact:true}).click();
  await page.getByRole('button',{name:'Archive conversation',exact:true}).click();
  await expect(page.getByRole('button',{name:'Restore to inbox',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:/ChatB Member/})).toHaveCount(0);
  await expect(b.getByRole('button',{name:/ChatA Member/})).toBeVisible();
  await page.reload();await page.getByRole('button',{name:'Archived',exact:true}).click();
  await page.getByRole('button',{name:/ChatB Member/}).click();
  await expect(page.getByRole('button',{name:'Restore to inbox',exact:true})).toBeVisible();
  const wake='A reply restores the inbox '+Date.now();
  await b.getByRole('textbox',{name:'Message',exact:true}).fill(wake);
  await b.getByRole('button',{name:'Send message',exact:true}).click();
  await expect(b.getByRole('textbox',{name:'Message',exact:true})).toHaveValue('');
  await expect(page.getByText(wake,{exact:true})).toBeVisible({timeout:15000});
  await expect(page.getByRole('button',{name:'Archive conversation',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Inbox',exact:true}).click();
  await expect(page.getByRole('button',{name:/ChatB Member/})).toBeVisible();
  await page.getByRole('button',{name:'Archive conversation',exact:true}).click();
  await page.getByRole('button',{name:'Restore to inbox',exact:true}).click();
  await expect(page.getByRole('button',{name:'Archive conversation',exact:true})).toBeVisible();
  if(await page.getByRole('button',{name:'Clear search',exact:true}).count())await page.getByRole('button',{name:'Clear search',exact:true}).click();
  await page.getByRole('button',{name:'Unstar conversation',exact:true}).click();
  await expect(page.getByRole('button',{name:'Star conversation',exact:true})).toBeVisible();
  expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
  await page.screenshot({path:testInfo.outputPath('messages-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  expect((await new AxeBuilder({page}).analyze()).violations).toEqual([]);
  await page.screenshot({path:testInfo.outputPath('messages-mobile.png'),fullPage:true});
  await b.goto('http://localhost:3100'+path);
  b.once('dialog',dialog=>dialog.accept());await b.getByRole('button',{name:'Block member',exact:true}).click();
  await expect(b.getByRole('button',{name:'Unblock ChatA Member',exact:true})).toBeVisible();
  await expect(page.getByText('Conversation unavailable. It may be blocked.',{exact:true})).toBeVisible({timeout:15000});
  await expect(page.getByText(missed,{exact:true})).toHaveCount(0);
 }finally{releaseLost();await page.unrouteAll({behavior:'ignoreErrors'});await page.context().setOffline(false);await second.close()}
});
