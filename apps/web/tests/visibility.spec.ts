import {test,expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import {register} from './helpers/register';
test.use({trace:'off'});
test('profile sharing is opt-in and disabling blocks another member',async({page,request,browser},testInfo)=>{
 await register(page,request,'Owner');
 const visibility=page.getByRole('region',{name:'Profile visibility',exact:true});
 await expect(visibility.getByRole('checkbox',{name:'Visible to signed-in members',exact:true})).not.toBeChecked();
 const path=await visibility.getByRole('link',{name:'View member profile'}).getAttribute('href');
 const context=await browser.newContext();try{
 const visitor=await context.newPage();await register(visitor,request,'Visitor');
 await visitor.goto(`http://localhost:3100${path}`);
 await expect(visitor.getByRole('status')).toHaveText('Profile unavailable or private.');
 await visibility.getByRole('checkbox',{name:'Visible to signed-in members',exact:true}).click();await expect(visibility.getByText('Visibility saved.',{exact:true})).toBeVisible();
 await visitor.getByRole('button',{name:'Refresh profile'}).click();
 await expect(visitor.getByRole('heading',{name:'Owner Member',exact:true})).toBeVisible();
 await visitor.getByRole('button',{name:'Connect',exact:true}).click();
 await expect(visitor.getByText('Connection request sent.',{exact:true})).toBeVisible();
 const ownerNetwork=page.getByRole('region',{name:'My network',exact:true});
 await ownerNetwork.getByRole('button',{name:'Reload network',exact:true}).click();
 await expect(ownerNetwork.getByRole('heading',{name:'Visitor Member',exact:true})).toBeVisible();
 await visitor.goto('http://localhost:3100/notifications');
 await expect(visitor.getByText('Live updates connected.',{exact:true})).toBeVisible();
 const mirror=await context.newPage();await mirror.goto('http://localhost:3100/notifications');
 await expect(mirror.getByText('Live updates connected.',{exact:true})).toBeVisible();
 await ownerNetwork.getByRole('button',{name:'Accept invitation',exact:true}).click();
 await expect(ownerNetwork.getByText('Connections: 1',{exact:true})).toBeVisible();
 await expect(visitor.getByRole('article',{name:'Notification from Owner Member',exact:true})).toHaveCount(1,{timeout:20000});
 await expect(mirror.getByText('Unread: 1',{exact:true})).toBeVisible();
 await expect(visitor.getByText('Unread: 1',{exact:true})).toBeVisible();
 await visitor.getByRole('button',{name:'Mark read',exact:true}).click();
 await expect(visitor.getByText('Unread: 0',{exact:true})).toBeVisible();
 await expect(mirror.getByText('Unread: 0',{exact:true})).toBeVisible();
 await visitor.reload();await expect(visitor.getByText('Unread: 0',{exact:true})).toBeVisible();
 const notifications=visitor.getByRole('checkbox',{name:'New connection notifications'});
 await notifications.click();await expect(visitor.getByRole('status')).toHaveText('Notification preferences saved.');
 await expect(mirror.getByRole('checkbox',{name:'New connection notifications'})).not.toBeChecked();
 await visitor.reload();await expect(notifications).not.toBeChecked();
 await notifications.click();await expect(visitor.getByRole('status')).toHaveText('Notification preferences saved.');
 await expect(mirror.getByRole('checkbox',{name:'New connection notifications'})).toBeChecked();
 expect((await new AxeBuilder({page:visitor}).analyze()).violations).toEqual([]);
 await expect(visitor.getByRole('link',{name:'Notifications',exact:true})).toHaveAttribute('aria-current','page');
 await visitor.screenshot({path:testInfo.outputPath('notifications-desktop.png'),fullPage:true});
 await visitor.setViewportSize({width:390,height:844});
 expect(await visitor.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 expect((await new AxeBuilder({page:visitor}).analyze()).violations).toEqual([]);
 await visitor.screenshot({path:testInfo.outputPath('notifications-mobile.png'),fullPage:true});
 await visitor.setViewportSize({width:1280,height:720});

 await visitor.goto('http://localhost:3100');
 const visitorNetwork=visitor.getByRole('region',{name:'My network',exact:true});
 await expect(visitorNetwork.getByText('Connections: 1',{exact:true})).toBeVisible();
 visitor.once('dialog',dialog=>dialog.accept());
 await visitorNetwork.getByRole('button',{name:'Remove connection',exact:true}).click();
 await expect(visitorNetwork.getByText('Connections: 0',{exact:true})).toBeVisible();
 await expect(mirror.getByRole('article')).toHaveCount(0);
 await mirror.close();
 await ownerNetwork.getByRole('button',{name:'Reload network',exact:true}).click();
 await expect(ownerNetwork.getByText('Connections: 0',{exact:true})).toBeVisible();
 await visitor.goto(`http://localhost:3100${path}`);
 await visitor.getByRole('button',{name:'Connect',exact:true}).click();
 await expect(visitor.getByText('Connection request sent.',{exact:true})).toBeVisible();
 await visitor.goto('http://localhost:3100');
 await visitorNetwork.getByRole('button',{name:'Withdraw invitation',exact:true}).click();
 await expect(visitorNetwork.getByRole('button',{name:'Withdraw invitation',exact:true})).toHaveCount(0);
 await visitor.goto(`http://localhost:3100${path}`);
 await visitor.getByRole('button',{name:'Connect',exact:true}).click();
 await expect(visitor.getByText('Connection request sent.',{exact:true})).toBeVisible();
 await ownerNetwork.getByRole('button',{name:'Reload network',exact:true}).click();
 await ownerNetwork.getByRole('button',{name:'Ignore invitation',exact:true}).click();
 await expect(ownerNetwork.getByRole('button',{name:'Ignore invitation',exact:true})).toHaveCount(0);
 visitor.once('dialog',dialog=>dialog.accept());
 await visitor.getByRole('button',{name:'Block member',exact:true}).click();
 const blocks=visitor.getByRole('region',{name:'Blocked members',exact:true});
 await expect(blocks.getByRole('button',{name:'Unblock Owner Member',exact:true})).toBeVisible();
 await visitor.goto(`http://localhost:3100${path}`);
 await expect(visitor.getByRole('status')).toHaveText('Profile unavailable or private.');
 const targetId=path!.split('/').pop();
 const csrf=await (await visitor.request.get('http://localhost:3100/api/v1/csrf')).json();
 expect((await visitor.request.post('http://localhost:3100/api/v1/network',{headers:{[csrf.header]:csrf.token},data:{id:crypto.randomUUID(),recipientId:targetId}})).status()).toBe(409);
 await visitor.goto('http://localhost:3100');
 visitor.once('dialog',dialog=>dialog.accept());
 await blocks.getByRole('button',{name:'Unblock Owner Member',exact:true}).click();
 await expect(blocks.getByRole('button',{name:'Unblock Owner Member',exact:true})).toHaveCount(0);
 await visitor.goto(`http://localhost:3100${path}`);
 await expect(visitor.getByRole('heading',{name:'Owner Member',exact:true})).toBeVisible();
 await page.reload();await expect(visibility.getByRole('checkbox',{name:'Visible to signed-in members',exact:true})).toBeChecked();
 await visibility.getByRole('checkbox',{name:'Visible to signed-in members',exact:true}).click();await expect(visibility.getByText('Visibility saved.',{exact:true})).toBeVisible();
 await visitor.getByRole('button',{name:'Refresh profile'}).click();
 await expect(visitor.getByRole('status')).toHaveText('Profile unavailable or private.');
 await expect(visitor.getByRole('heading',{name:'Owner Member',exact:true})).toHaveCount(0);
 }finally{await context.close()}
});
